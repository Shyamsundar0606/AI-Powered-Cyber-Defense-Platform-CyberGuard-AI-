import re
from typing import Any
from uuid import uuid4

from app.schemas.detection import DetectionRuleResponse, DetectionSeverity
from app.services.mitre_mapper import enrich_technique_mapping

POWERSHELL_KEYWORDS = ["encodedcommand", "frombase64string", "downloadstring", "invoke-expression"]
AUTH_KEYWORDS = ["failed login", "brute force", "password spraying", "invalid password", "4625"]
FILE_KEYWORDS = ["suspicious executable", "process injection", "payload", "dropper", "malware"]


def generate_sigma_rule(input_data: dict[str, Any]) -> str:
    title = str(input_data.get("title", "CyberGuard Detection"))
    description = str(input_data.get("description", "Generated detection rule."))
    log_source = str(input_data.get("log_source", "windows_security"))
    behavior = _combined_text(input_data)
    rule_id = str(uuid4())

    if _is_auth_behavior(behavior, input_data):
        return _sigma_auth_bruteforce(title, description, rule_id)
    if _is_powershell_behavior(behavior, input_data):
        return _sigma_powershell(title, description, rule_id)
    if log_source == "linux_auth":
        return _sigma_linux_auth(title, description, rule_id)
    if log_source == "cloudtrail":
        return _sigma_cloudtrail(title, description, rule_id)
    if log_source == "web_server":
        return _sigma_web_server(title, description, rule_id)
    return _sigma_generic(title, description, rule_id, log_source)


def generate_yara_rule(input_data: dict[str, Any]) -> str:
    title = str(input_data.get("title", "CyberGuard Detection"))
    severity = _determine_severity(input_data).lower()
    mitre_ids = _normalize_mitre_ids(input_data.get("mitre_technique_ids", []))
    behavior = _combined_text(input_data)
    strings = _extract_yara_strings(behavior)
    rule_name = _safe_rule_name(title)

    string_lines = "\n".join(
        f'        $s{index} = "{value}" nocase'
        for index, value in enumerate(strings, start=1)
    )

    return f"""rule {rule_name}
{{
    meta:
        description = "Generated by CyberGuard AI"
        author = "CyberGuard AI"
        severity = "{severity}"
        mitre = "{', '.join(mitre_ids) if mitre_ids else 'unmapped'}"

    strings:
{string_lines}

    condition:
        any of them
}}"""


def generate_detection_package(input_data: dict[str, Any]) -> DetectionRuleResponse:
    mitre_ids = _normalize_mitre_ids(input_data.get("mitre_technique_ids", []))
    context = _combined_text(input_data)
    severity = _determine_severity(input_data)
    mitre_mappings = enrich_technique_mapping(mitre_ids, context)

    return DetectionRuleResponse(
        sigma_rule=generate_sigma_rule(input_data),
        yara_rule=generate_yara_rule(input_data),
        explanation=_build_explanation(input_data, severity),
        false_positive_notes=_false_positives(input_data),
        recommended_log_sources=_recommended_log_sources(input_data),
        mitre_mappings=mitre_mappings,
        severity=severity,
    )


