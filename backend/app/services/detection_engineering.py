def _determine_severity(input_data: dict[str, Any]) -> DetectionSeverity:
    text = _combined_text(input_data)
    mitre_ids = set(_normalize_mitre_ids(input_data.get("mitre_technique_ids", [])))
    if _is_powershell_behavior(text, input_data) or {"T1059", "T1055", "T1105"} & mitre_ids:
        return "Critical"
    if _is_auth_behavior(text, input_data) or {"T1110", "T1078", "T1041"} & mitre_ids:
        return "High"
    return "Medium"


def _build_explanation(input_data: dict[str, Any], severity: DetectionSeverity) -> str:
    title = input_data.get("title", "this behavior")
    log_source = input_data.get("log_source", "the selected logs")
    return (
        f"This {severity.lower()} severity detection package turns the alert context for "
        f"'{title}' into a Sigma rule for {log_source} telemetry and a companion YARA rule "
        "using safe, behavior-oriented strings. Review thresholds and field names against "
        "your SIEM schema before production use."
    )


def _false_positives(input_data: dict[str, Any]) -> list[str]:
    text = _combined_text(input_data)
    if _is_auth_behavior(text, input_data):
        return ["User forgot password", "Misconfigured service account", "Password rotation scripts"]
    if _is_powershell_behavior(text, input_data):
        return ["Administrator automation", "Software deployment scripts", "Security tooling"]
    if any(keyword in text for keyword in FILE_KEYWORDS):
        return ["Internal software packaging", "Endpoint security test files", "Developer tooling"]
    return ["Expected administrative activity", "Vulnerability scanning", "Security validation exercises"]


def _recommended_log_sources(input_data: dict[str, Any]) -> list[str]:
    log_source = input_data.get("log_source")
    if log_source == "windows_security":
        return ["Windows Security Event Log", "Identity provider authentication logs", "VPN authentication logs"]
    if log_source == "powershell":
        return ["PowerShell Script Block Logs", "Windows Security Event 4688", "Sysmon Process Creation"]
    if log_source == "sysmon":
        return ["Sysmon Process Creation", "Sysmon Network Connection", "EDR process telemetry"]
    if log_source == "linux_auth":
        return ["Linux auth.log", "SSHD logs", "PAM authentication logs"]
    if log_source == "web_server":
        return ["Web access logs", "WAF alerts", "Reverse proxy logs"]
    if log_source == "cloudtrail":
        return ["AWS CloudTrail", "IAM Access Analyzer", "Cloud identity provider logs"]
    return ["SIEM normalized security events", "Endpoint telemetry", "Identity provider logs"]


def _extract_yara_strings(text: str) -> list[str]:
    candidates = [
        "powershell",
        "encodedcommand",
        "frombase64string",
        "downloadstring",
        "invoke-expression",
        "failed login",
        "invalid password",
        "process injection",
        "suspicious executable",
        "download cradle",
    ]
    matched = [candidate for candidate in candidates if candidate in text]
    if len(matched) >= 3:
        return matched[:6]

    words = re.findall(r"[a-zA-Z][a-zA-Z0-9_-]{4,}", text)
    safe_words = []
    for word in words:
        lowered = word.lower()
        if lowered not in safe_words and lowered not in {"description", "suspicious", "behavior"}:
            safe_words.append(lowered)
        if len(safe_words) == 6:
            break
    return (matched + safe_words + ["suspicious", "behavior", "cyberguard"])[:6]


def _safe_rule_name(title: str) -> str:
    name = re.sub(r"[^A-Za-z0-9_]+", "_", title.strip())
    name = re.sub(r"_+", "_", name).strip("_")
    if not name:
        name = "CyberGuard_Detection"
    if name[0].isdigit():
        name = f"Rule_{name}"
    return name[:80]


def _combined_text(input_data: dict[str, Any]) -> str:
    return " ".join(
        [
            str(input_data.get("title", "")),
            str(input_data.get("description", "")),
            str(input_data.get("log_source", "")),
            str(input_data.get("suspicious_behavior", "")),
        ]
    ).lower()


def _normalize_mitre_ids(values: Any) -> list[str]:
    if not isinstance(values, list):
        return []
    normalized = []
    for value in values:
        technique_id = str(value).strip().upper()
        if re.fullmatch(r"T\d{4}", technique_id) and technique_id not in normalized:
            normalized.append(technique_id)
    return normalized


def _is_auth_behavior(text: str, input_data: dict[str, Any]) -> bool:
    return input_data.get("log_source") == "windows_security" or any(keyword in text for keyword in AUTH_KEYWORDS)


def _is_powershell_behavior(text: str, input_data: dict[str, Any]) -> bool:
    return input_data.get("log_source") == "powershell" or any(keyword in text for keyword in POWERSHELL_KEYWORDS)
